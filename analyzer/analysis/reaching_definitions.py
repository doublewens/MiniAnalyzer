"""Classic, forward, intraprocedural *may* reaching-definitions analysis.

One static definition is identified by ``variable@instruction_index``, for example
``x@4``.  A call with an assigned result also defines its result variable.

The domain is the powerset of all static definitions in this Teaching IR program;
the order is subset inclusion and the join is set union.  Starting from the
empty set and using GEN/KILL monotone transfer yields a finite fixed point.

Limitations follow the teaching IR: calls have no modeled side effects,
there are no procedure-entry parameter definitions, and the v0.3-compatible
solver schedules even unreachable CFG nodes.  See docs/reaching_definitions.md.
"""
from __future__ import annotations

from analyzer.dataflow.analysis import DataflowAnalysis, Direction
from analyzer.dataflow.fact import SetFact


class ReachingDefinitionsAnalysis(DataflowAnalysis):
    """May-reach static assignments on the existing instruction-level CFG."""

    def __init__(self, program, cfg):
        super().__init__(program, cfg)
        # Build from all static instructions (also deliberately includes
        # unreachable instructions, mirroring the existing CFG/solver scope).
        self._definitions_by_variable: dict[str, set[str]] = {}
        self._generated: dict[int, set[str]] = {}
        for inst in program.instructions:
            generated = {f"{variable}@{inst.index}" for variable in inst.def_vars()}
            self._generated[inst.index] = generated
            for variable in inst.def_vars():
                self._definitions_by_variable.setdefault(variable, set()).add(
                    f"{variable}@{inst.index}"
                )

        self._killed: dict[int, set[str]] = {}
        for inst in program.instructions:
            overwritten = set()
            for variable in inst.def_vars():
                overwritten.update(self._definitions_by_variable[variable])
            # The definition generated by this instruction is never in KILL.
            self._killed[inst.index] = overwritten - self._generated[inst.index]

    @property
    def name(self) -> str:
        return "reaching-definitions"

    @property
    def direction(self) -> Direction:
        return Direction.FORWARD

    def new_initial_fact(self) -> SetFact:
        return SetFact()

    def new_boundary_fact(self) -> SetFact:
        # IR inputs/parameters are not modeled as explicit initial definitions.
        return SetFact()

    def meet(self, facts) -> SetFact:
        result: set[str] = set()
        for fact in facts:
            result.update(fact.values)
        return SetFact(result)

    def gen(self, node: int) -> set[str]:
        """Return a *copy* of the definitions created by this instruction."""
        return set(self._generated[node])

    def kill(self, node: int) -> set[str]:
        """Return a *copy* of other definitions overwritten by this node."""
        return set(self._killed[node])

    def transfer_node(self, node: int, in_fact: SetFact) -> SetFact:
        return SetFact((in_fact.values - self._killed[node]) | self._generated[node])
